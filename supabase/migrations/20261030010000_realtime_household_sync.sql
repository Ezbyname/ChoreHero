-- Realtime change notifications for household screens.
--
-- Adds the tables whose changes a family member must see without signing
-- out and back in to the supabase_realtime publication:
--   tasks                — every task-completion transition (submit,
--                          withdraw, approve, reject) changes tasks.status,
--                          so this one table covers the whole Task
--                          Completion V2 lifecycle;
--   contribution_claims  — "Did you do something helpful?" claims;
--   reward_redemptions   — reward requests;
--   rewards              — new / archived rewards.
--
-- Deliberately NOT added: task_completion_submissions (its rows carry
-- photo_storage_path, which clients never need to receive) and
-- task_completion_submission_photos (no client access at all). The app
-- treats every Realtime event as a "something changed — refetch" signal
-- only and never reads the payload, so tasks.status changes are enough.
--
-- Security: Supabase Realtime delivers postgres_changes to a subscriber
-- only for rows that subscriber can SELECT under the table's existing RLS
-- policies. No policy, grant, or table privilege is changed here.
--
-- Idempotent: each table is added only if it is not already published.
--
-- Migration history rule: do not edit this file after it is applied.

DO $$
DECLARE
  v_table text;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime') THEN
    CREATE PUBLICATION supabase_realtime;
  END IF;

  FOREACH v_table IN ARRAY ARRAY['tasks', 'contribution_claims', 'reward_redemptions', 'rewards'] LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pg_publication_tables
      WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = v_table
    ) THEN
      EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I', v_table);
    END IF;
  END LOOP;
END $$;
