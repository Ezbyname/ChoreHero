-- Task Completion V2 — child withdrawal, part 1: add the WITHDRAWN
-- submission status.
--
-- A child may take back their own still-PENDING completion request
-- ("I'm not actually done" / "I want to add or change the photo"). This is
-- a distinct domain event from an adult REJECTING it:
--
--   REJECTED  = adult reviewed and sent the task back
--   WITHDRAWN = the submitting child took the request back before review
--
-- Kept as its own migration file, in its own transaction, ahead of any
-- statement that references the literal 'withdrawn' value (the next
-- migration's CHECK constraint and RPC body) — Postgres does not allow a
-- newly-added enum value to be used in the same transaction that added
-- it. Same pattern as 20260830000000_reward_redemption_cancelled_status.sql.
--
-- Additive only: existing pending/approved/rejected rows are unaffected.
-- uq_tcs_one_pending_per_task (WHERE status = 'pending') automatically
-- stops counting a row once it becomes 'withdrawn'.
--
-- Migration history rule: do not edit this file after it is applied.

ALTER TYPE task_completion_submission_status ADD VALUE 'withdrawn';
