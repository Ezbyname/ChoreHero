-- Reward Reserved Points — Slice 1: add the CANCELLED redemption status.
--
-- Product model change: reward requests now reserve points immediately
-- (see the next migration for the accounting/RPC changes). A child may
-- withdraw their own still-PENDING request ("Changed my mind"). This is
-- a distinct domain event from an adult REJECTING a request:
--
--   REJECTED  = adult declined the request
--   CANCELLED = child withdrew the request
--
-- Kept as its own migration file, in its own transaction, ahead of any
-- statement that references the literal 'cancelled' value (the next
-- migration's CHECK constraint and RPC body) — Postgres does not allow
-- a newly-added enum value to be used in the same transaction that added
-- it.
--
-- Additive only: existing pending/approved/rejected rows are entirely
-- unaffected by adding a new enum value.
--
-- Migration history rule: do not edit this file after it is applied.

ALTER TYPE reward_redemption_status ADD VALUE 'cancelled';
