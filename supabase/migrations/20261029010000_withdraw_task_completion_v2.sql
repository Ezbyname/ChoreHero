-- Task Completion V2 — child withdrawal, part 2: review-metadata CHECK +
-- withdraw_task_completion_v2 RPC.
--
-- Contract
--   withdraw_task_completion_v2(p_submission_id uuid)
--     RETURNS task_completion_submissions
--
--   Allowed only when ALL hold:
--     - caller is authenticated;
--     - caller is the submission's submitted_by_profile_id;
--     - caller is still a CHILD member of the submission's household (an
--       owner/admin/adult can never use this as a stand-in for Reject —
--       V2 submissions are only ever created by children, and the role
--       check is re-asserted here regardless);
--     - the submission is 'pending' and belongs to its task;
--     - the task is 'needs_attention' (waiting for review).
--
--   Effect (one transaction):
--     submission  pending          -> withdrawn   (reviewed_* stay NULL)
--     task        needs_attention  -> open
--   No points move (points are only ever awarded by approve). The evidence
--   object is untouched: photo_storage_path stays on the withdrawn row and
--   uq_tcs_photo_storage_path keeps it bound there, so the same object can
--   never be re-attached to a later submission. Nothing in Storage is
--   updated or deleted, and no table/Storage grant or policy changes here.
--
--   Re-sending after a withdrawal is an ordinary request_task_completion_v2
--   call with a NEW client_request_id (and, with a photo, a NEW
--   photo_object_id) — the task is 'open' again, and the partial unique
--   index uq_tcs_one_pending_per_task no longer counts the withdrawn row.
--
-- Errors
--   28000  not authenticated / not authorized (unknown submission, not the
--          submitter, not a child member) — collapsed, like approve/reject,
--          so the RPC never reveals whether a submission exists.
--   CH017  submission is not pending review (approved or rejected — also
--          what a reviewer racing this call receives when withdrawal wins).
--   CH019  workflow invariant violated (task missing / household mismatch /
--          pending submission whose task is not needs_attention).
--
-- Idempotency
--   Calling again for a submission the same caller already withdrew
--   returns that row unchanged — no second state change, no error.
--
-- Concurrency
--   Same lock order as approve_task_completion_v2 / reject_task_completion_v2:
--   read the submission's task id (no lock), lock the TASK row FOR UPDATE,
--   then lock the SUBMISSION row FOR UPDATE, then transition with a guarded
--   `WHERE status = 'pending'`. A racing approve/reject/withdraw therefore
--   serializes on the task row; exactly one wins and the others see the
--   committed status and fail deterministically (CH017), or — for a repeat
--   withdraw — get the idempotent replay.
--
-- Migration history rule: do not edit this file after it is applied.

-- ── Review-metadata consistency: allow WITHDRAWN with no reviewer ─────────

ALTER TABLE task_completion_submissions
  DROP CONSTRAINT chk_tcs_review_metadata_consistency;

ALTER TABLE task_completion_submissions
  ADD CONSTRAINT chk_tcs_review_metadata_consistency CHECK (
    (status IN ('pending', 'withdrawn') AND reviewed_by_profile_id IS NULL AND reviewed_at IS NULL)
    OR
    (status IN ('approved', 'rejected') AND reviewed_at IS NOT NULL)
  );

-- ── withdraw_task_completion_v2 ───────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.withdraw_task_completion_v2(p_submission_id uuid)
RETURNS public.task_completion_submissions
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_caller       uuid := auth.uid();
  v_task_id      uuid;
  v_household_id uuid;
  v_submitter    uuid;
  v_task         tasks%ROWTYPE;
  v_submission   task_completion_submissions%ROWTYPE;
BEGIN
  IF v_caller IS NULL THEN
    RAISE EXCEPTION 'Not authenticated' USING ERRCODE = '28000';
  END IF;

  SELECT task_id, household_id, submitted_by_profile_id
    INTO v_task_id, v_household_id, v_submitter
  FROM task_completion_submissions
  WHERE id = p_submission_id;

  IF NOT FOUND
     OR v_submitter IS DISTINCT FROM v_caller
     OR NOT internal.is_household_member(
          v_household_id, v_caller, ARRAY['child']::household_member_role[]
        ) THEN
    RAISE EXCEPTION 'Not authorized' USING ERRCODE = '28000';
  END IF;

  SELECT * INTO v_task FROM tasks WHERE id = v_task_id FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Workflow invariant violated: referenced task missing' USING ERRCODE = 'CH019';
  END IF;

  SELECT * INTO v_submission FROM task_completion_submissions WHERE id = p_submission_id FOR UPDATE;

  IF v_submission.household_id IS DISTINCT FROM v_task.household_id
     OR v_submission.task_id IS DISTINCT FROM v_task.id THEN
    RAISE EXCEPTION 'Workflow invariant violated: submission/task mismatch' USING ERRCODE = 'CH019';
  END IF;

  -- Idempotent replay: already withdrawn by this same caller (checked
  -- above). Re-checked here, under the lock, so the answer is consistent
  -- with the committed state.
  IF v_submission.status = 'withdrawn' THEN
    RETURN v_submission;
  END IF;

  IF v_submission.status <> 'pending' THEN
    RAISE EXCEPTION 'Submission is not pending review' USING ERRCODE = 'CH017';
  END IF;

  IF v_task.status <> 'needs_attention' THEN
    RAISE EXCEPTION 'Workflow invariant violated: pending submission on a task not awaiting review' USING ERRCODE = 'CH019';
  END IF;

  UPDATE task_completion_submissions
  SET status     = 'withdrawn',
      updated_at = now()
  WHERE id = p_submission_id AND status = 'pending'
  RETURNING * INTO v_submission;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Submission is not pending review' USING ERRCODE = 'CH017';
  END IF;

  UPDATE tasks
  SET status = 'open'
  WHERE id = v_task_id AND status = 'needs_attention';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Workflow invariant violated: task/submission transition mismatch' USING ERRCODE = 'CH019';
  END IF;

  RETURN v_submission;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.withdraw_task_completion_v2(uuid) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.withdraw_task_completion_v2(uuid) FROM anon;
GRANT  EXECUTE ON FUNCTION public.withdraw_task_completion_v2(uuid) TO authenticated;
GRANT  EXECUTE ON FUNCTION public.withdraw_task_completion_v2(uuid) TO service_role;
