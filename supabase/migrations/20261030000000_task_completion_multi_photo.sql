-- Task Completion V2 — up to 5 evidence photos per completion attempt.
--
-- Additive and backward compatible. Nothing here edits an applied
-- migration, changes an existing function body, or widens any client
-- privilege:
--
--   * photo 1 keeps living in task_completion_submissions.photo_storage_path
--     exactly as today, so every existing row (0 or 1 photo), the existing
--     Storage SELECT policy, the deployed task-completion-evidence Edge
--     Function, and already-installed app builds keep working unchanged;
--   * photos 2..5 live in a NEW table, task_completion_submission_photos
--     (positions 1..4), with NO client privilege of any kind — it is read
--     only by the Edge Function's service-role client, and only after the
--     caller-scoped authorization query on task_completion_submissions has
--     already succeeded (see supabase/functions/task-completion-evidence);
--   * photo_count is a generated, metadata-only column clients can read
--     (it is covered by authenticated's existing table-level SELECT and the
--     existing RLS policy) so lists can show "📷 3" without ever touching
--     evidence bytes or storage paths;
--   * request_task_completion_v3 accepts 0..5 photo object ids. It delegates
--     the whole proven attempt state machine (routing lookup / CH014
--     no-oracle, task-first lock, CREATE vs REPLAY authorization, open ->
--     needs_attention CAS, photo-1 CH015/CH018, idempotent replay) to the
--     UNCHANGED request_task_completion_v2, then attaches photos 2..5 inside
--     the same transaction.
--
-- Evidence immutability
--   Extra photos are inserted only by request_task_completion_v3, in the
--   same transaction that creates the submission (extra_photo_count is set
--   in that same transaction, before commit, so no reader can ever observe
--   a partial set). No UPDATE/DELETE path exists for any client role on
--   either table. No Storage UPDATE/DELETE policy is added.
--
-- One object, one submission
--   uq_tcs_photo_storage_path (existing) covers photo 1;
--   uq_tcsp_storage_path covers photos 2..5; and because an object id must
--   never move between the two columns either, v3 checks both before
--   attaching, and trg_tcs_photo_path_not_extra stops request_task_completion_v2
--   (old clients) from attaching an object already used as an extra photo.
--   Withdrawal leaves every photo bound to the withdrawn row.
--
-- Errors (v3, in addition to everything v2 raises)
--   CH021  invalid evidence set: more than 5 ids, a NULL id, or a duplicate id
--   CH014  idempotency key reused with a different photo set
--   CH015  an extra evidence object does not exist (whole attempt rolls back:
--          the task stays 'open', no submission row exists)
--   CH018  an extra evidence object is already attached to a submission
--
-- Migration history rule: do not edit this file after it is applied.

-- ── Metadata columns ─────────────────────────────────────────────────────

ALTER TABLE task_completion_submissions
  ADD COLUMN extra_photo_count smallint NOT NULL DEFAULT 0;

ALTER TABLE task_completion_submissions
  ADD CONSTRAINT chk_tcs_extra_photo_count CHECK (
    extra_photo_count BETWEEN 0 AND 4
    AND (photo_storage_path IS NOT NULL OR extra_photo_count = 0)
  );

ALTER TABLE task_completion_submissions
  ADD COLUMN photo_count smallint GENERATED ALWAYS AS (
    ((CASE WHEN photo_storage_path IS NULL THEN 0 ELSE 1 END) + extra_photo_count)::smallint
  ) STORED;

-- ── Photos 2..5 ──────────────────────────────────────────────────────────

CREATE TABLE task_completion_submission_photos (
  submission_id uuid        NOT NULL REFERENCES task_completion_submissions (id) ON DELETE CASCADE,
  position      smallint    NOT NULL,
  storage_path  text        NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT pk_tcsp PRIMARY KEY (submission_id, position),
  -- position 0 is photo_storage_path on the submission row itself.
  CONSTRAINT chk_tcsp_position CHECK (position BETWEEN 1 AND 4),
  CONSTRAINT uq_tcsp_storage_path UNIQUE (storage_path)
);

ALTER TABLE task_completion_submission_photos ENABLE ROW LEVEL SECURITY;

-- No client role may read or write this table — not even SELECT. Paths are
-- resolved server-side by the Edge Function's service-role client only.
-- No policy is created: RLS default-deny is a second, independent layer.
REVOKE ALL ON public.task_completion_submission_photos FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.task_completion_submission_photos TO service_role;

-- ── An extra photo's object can never become a photo-1 object ────────────

CREATE OR REPLACE FUNCTION internal.tcs_photo_path_not_extra()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.photo_storage_path IS NOT NULL AND EXISTS (
    SELECT 1 FROM task_completion_submission_photos WHERE storage_path = NEW.photo_storage_path
  ) THEN
    RAISE EXCEPTION 'Evidence object already attached to another submission' USING ERRCODE = 'CH018';
  END IF;
  RETURN NEW;
END;
$$;

REVOKE EXECUTE ON FUNCTION internal.tcs_photo_path_not_extra() FROM PUBLIC;

CREATE TRIGGER trg_tcs_photo_path_not_extra
  BEFORE INSERT ON task_completion_submissions
  FOR EACH ROW EXECUTE FUNCTION internal.tcs_photo_path_not_extra();

-- ── request_task_completion_v3 ───────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.request_task_completion_v3(
  p_task_id            uuid,
  p_client_request_id  uuid,
  p_photo_object_ids   uuid[] DEFAULT '{}'
)
RETURNS public.task_completion_submissions
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_caller      uuid   := auth.uid();
  v_ids         uuid[] := coalesce(p_photo_object_ids, '{}');
  v_n           int;
  v_existed     boolean;
  v_submission  task_completion_submissions%ROWTYPE;
  v_prefix      text;
  v_extra_paths text[] := '{}';
  v_stored      text[];
  i             int;
BEGIN
  IF v_caller IS NULL THEN
    RAISE EXCEPTION 'Not authenticated' USING ERRCODE = '28000';
  END IF;

  v_n := coalesce(array_length(v_ids, 1), 0);

  IF v_n > 5
     OR array_position(v_ids, NULL) IS NOT NULL
     OR (SELECT count(DISTINCT x) FROM unnest(v_ids) AS x) <> v_n THEN
    RAISE EXCEPTION 'Invalid evidence photo set' USING ERRCODE = 'CH021';
  END IF;

  -- Unlocked; only used below to tell "created by this call" apart from
  -- "replayed". The caller's own key, so it can never reveal anything.
  SELECT EXISTS (
    SELECT 1 FROM task_completion_submissions
    WHERE submitted_by_profile_id = v_caller AND client_request_id = p_client_request_id
  ) INTO v_existed;

  -- The unchanged v2 state machine: locks the task row FIRST (held until
  -- this transaction ends, which serializes every competing attempt on the
  -- task), authorizes, and either creates the row with photo 1 or replays.
  SELECT * INTO v_submission
  FROM public.request_task_completion_v2(
    p_task_id,
    p_client_request_id,
    CASE WHEN v_n > 0 THEN v_ids[1] ELSE NULL END
  );

  -- Same formula v2 uses for photo 1.
  v_prefix := v_submission.household_id || '/' || p_task_id || '/' || v_caller || '/';
  FOR i IN 2 .. v_n LOOP
    v_extra_paths := v_extra_paths || (v_prefix || v_ids[i]);
  END LOOP;

  SELECT coalesce(array_agg(storage_path ORDER BY position), '{}')
    INTO v_stored
  FROM task_completion_submission_photos
  WHERE submission_id = v_submission.id;

  IF NOT v_existed AND v_submission.created_at = now() AND cardinality(v_stored) = 0 THEN
    -- CREATE: the row was inserted by this very call.
    IF v_n <= 1 THEN
      RETURN v_submission;
    END IF;

    FOR i IN 1 .. cardinality(v_extra_paths) LOOP
      IF NOT EXISTS (
        SELECT 1 FROM storage.objects
        WHERE bucket_id = 'task-completion-evidence' AND name = v_extra_paths[i]
      ) THEN
        RAISE EXCEPTION 'Evidence object not found' USING ERRCODE = 'CH015';
      END IF;
    END LOOP;

    IF EXISTS (
      SELECT 1 FROM task_completion_submissions WHERE photo_storage_path = ANY (v_extra_paths)
    ) OR EXISTS (
      SELECT 1 FROM task_completion_submission_photos
      WHERE storage_path = ANY (v_extra_paths || v_submission.photo_storage_path)
    ) THEN
      RAISE EXCEPTION 'Evidence object already attached to another submission' USING ERRCODE = 'CH018';
    END IF;

    BEGIN
      INSERT INTO task_completion_submission_photos (submission_id, position, storage_path)
      SELECT v_submission.id, ord::smallint, path
      FROM unnest(v_extra_paths) WITH ORDINALITY AS t(path, ord);
    EXCEPTION WHEN unique_violation THEN
      RAISE EXCEPTION 'Evidence object already attached to another submission' USING ERRCODE = 'CH018';
    END;

    UPDATE task_completion_submissions
    SET extra_photo_count = (v_n - 1)::smallint
    WHERE id = v_submission.id
    RETURNING * INTO v_submission;

    RETURN v_submission;
  END IF;

  -- REPLAY: v2 already re-authorized the caller and matched photo 1; the
  -- rest of the set must match exactly, in order.
  IF v_stored IS DISTINCT FROM v_extra_paths
     OR v_submission.extra_photo_count <> cardinality(v_extra_paths) THEN
    RAISE EXCEPTION 'client_request_id reused with different evidence' USING ERRCODE = 'CH014';
  END IF;

  RETURN v_submission;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.request_task_completion_v3(uuid, uuid, uuid[]) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.request_task_completion_v3(uuid, uuid, uuid[]) FROM anon;
GRANT  EXECUTE ON FUNCTION public.request_task_completion_v3(uuid, uuid, uuid[]) TO authenticated;
GRANT  EXECUTE ON FUNCTION public.request_task_completion_v3(uuid, uuid, uuid[]) TO service_role;
