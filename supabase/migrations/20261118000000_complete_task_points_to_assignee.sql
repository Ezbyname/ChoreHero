-- Slice 6B.2 — direct completion credits the task's assignee, not the
-- caller. Owner product decision (2026-11-18): "Points belong to the
-- effective task assignee. The actor performs the action. The assignee
-- receives the reward."
--
-- Scope: CREATE OR REPLACE of public.complete_task(uuid) only — same
-- signature, same SECURITY DEFINER, same grants. Nothing else changes:
-- approve_task_completion (v1) and approve_task_completion_v2 already
-- credit the assignee/submitter and are untouched; claim_open_task,
-- request_task_completion(_v2), reject paths, tables and RLS are
-- untouched. 20260816000000_award_task_completion_points.sql is NOT
-- edited (migration history rule) — this file supersedes its
-- complete_task body.
--
-- Root cause being fixed: the previous body set
--   completed_by_profile_id = v_caller   (auth.uid(), the pressing adult)
-- and then credited points_balances / point_transactions to
-- completed_by_profile_id — so an adult pressing Complete on a child's
-- task received the child's Points.
--
-- Effective assignee (no new field): tasks.assignee_profile_id. An
-- explicitly assigned task stores its assignee there; claim_open_task
-- (20260710000000) claims an open-to-anyone task by setting exactly that
-- column to the claimant. So for both cases the effective assignee is
-- assignee_profile_id, and an unclaimed open-to-anyone task is the one
-- with assignee_profile_id IS NULL.
--
-- New rule:
--   points recipient = completed_by_profile_id = tasks.assignee_profile_id
-- read from the row returned by the compare-and-swap UPDATE itself (never
-- from the earlier unlocked SELECT, never from the caller, never from any
-- request parameter — the function still accepts only p_task_id). This is
-- the same worker-credit rule approve_task_completion already applies
-- (docs/task-state-contract.md §11: completed_by_profile_id is the
-- person whose task it is, not the adult who pressed the button). The
-- acting adult stays recorded as point_transactions.created_by_profile_id,
-- exactly as before.
--
-- Unclaimed open-to-anyone task (assignee NULL): there is no valid
-- recipient yet, so it can no longer be directly completed — raises
-- CH022. Previously it completed and credited the caller, which is the
-- rejected behaviour itself. No app screen offers Complete on such a task
-- (TaskAdapter gives 'claim'; Adult Tasks gives "I'll do this"), so no
-- client flow loses anything; the client maps any non-CH002 code to its
-- generic 'failed' reason.
--
-- Unchanged on purpose:
--   - Authorization: still owner/admin/adult of the task's household
--     (internal.is_household_member with the same role list). Not
--     broadened.
--   - Atomicity / exactly-once: still one function body, no internal
--     COMMIT; the CAS UPDATE (status = 'open') raises before any ledger
--     write when it matches nothing, so a retry, a double tap or an
--     already-completed / waiting task never reaches the award.
--   - Zero-point tasks still write the +0 upsert and the ledger row, as
--     before.
--
-- Migration history rule: do not edit this file after it is applied.

CREATE OR REPLACE FUNCTION public.complete_task(p_task_id uuid)
RETURNS tasks
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_caller      uuid := auth.uid();
  v_task        tasks%ROWTYPE;
  v_new_balance integer;
BEGIN
  IF v_caller IS NULL THEN
    RAISE EXCEPTION 'Not authenticated' USING ERRCODE = '28000';
  END IF;

  SELECT * INTO v_task FROM tasks WHERE id = p_task_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Task not found' USING ERRCODE = 'P0002';
  END IF;

  IF NOT internal.is_household_member(
    v_task.household_id, v_caller, ARRAY['owner','admin','adult']::household_member_role[]
  ) THEN
    RAISE EXCEPTION 'Not authorized to complete this task' USING ERRCODE = '28000';
  END IF;

  IF v_task.status = 'open' AND v_task.assignee_profile_id IS NULL THEN
    RAISE EXCEPTION 'Task has no assignee to credit' USING ERRCODE = 'CH022';
  END IF;

  -- In the SET list, assignee_profile_id is the row's current value (the
  -- UPDATE never changes it), so the recipient is whoever holds the task
  -- at the moment of the CAS, not at the earlier unlocked SELECT.
  UPDATE tasks
  SET status                  = 'completed',
      completed_at            = now(),
      completed_by_profile_id = assignee_profile_id
  WHERE id = p_task_id
    AND status = 'open'
    AND assignee_profile_id IS NOT NULL
  RETURNING * INTO v_task;

  IF NOT FOUND THEN
    -- Not open (already completed, waiting for review, or otherwise
    -- moved) at the moment of the UPDATE, or lost a race. Aborts here —
    -- nothing below this point ever runs for a retry or a stale call.
    RAISE EXCEPTION 'Task is not open' USING ERRCODE = 'CH002';
  END IF;

  INSERT INTO points_balances (household_id, profile_id, balance)
  VALUES (v_task.household_id, v_task.assignee_profile_id, v_task.points)
  ON CONFLICT ON CONSTRAINT uq_points_balances_household_profile
  DO UPDATE SET balance = points_balances.balance + EXCLUDED.balance,
                updated_at = now()
  RETURNING balance INTO v_new_balance;

  INSERT INTO point_transactions
    (household_id, profile_id, type, amount, balance_after, task_id, created_by_profile_id)
  VALUES
    (v_task.household_id, v_task.assignee_profile_id, 'task_completed',
     v_task.points, v_new_balance, v_task.id, v_caller);

  RETURN v_task;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.complete_task(uuid) FROM PUBLIC;
GRANT  EXECUTE ON FUNCTION public.complete_task(uuid) TO authenticated;
